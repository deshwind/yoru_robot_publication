#!/usr/bin/env python3
"""Run-by-run comparison of a reproduction run set with the baseline.

Pairs each run of the reproduction set with the baseline run of the same
scenario and seed (both from extract_metrics.py output) and reports whether the
outcome, escalation depth and the error flags agree, and how far the timing,
distance and perception metrics are apart.

  python3 evaluation/scripts/extract_metrics.py --manifest evaluation/data/repro/manifest.csv \\
      --out evaluation/data/repro/metrics.csv
  python3 evaluation/scripts/compare_repro.py evaluation/data/repro/metrics.csv \\
      evaluation/results/repro_wsl

Writes <out>/runs.csv (one row per pair) and <out>/summary.md.
"""

import math
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
BASELINE = os.path.join(ROOT, 'evaluation', 'data', 'metrics.csv')
CATEGORICAL = ['outcome', 'escalation_depth', 'false_intervention', 'missed',
               'expected_outcome_match']
CONTINUOUS = ['t_conf', 't_w1', 't_s2', 't_a', 't_r', 'confirmation_latency',
              'detection_to_intervention', 'navigation_time', 'compliance_latency',
              'path_length', 'min_distance', 'warnings_delivered', 'confirmed_frames',
              'first_conf_C', 'cctv1_frame_hz', 'rtf']


def wilson(k, n, z=1.96):
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (c - h, c + h)


def same(a, b):
    a, b = ('' if pd.isna(a) else str(a)), ('' if pd.isna(b) else str(b))
    try:
        return float(a) == float(b)
    except ValueError:
        return a == b


def main():
    repro_path, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    rep = pd.read_csv(repro_path, dtype=str, keep_default_na=False)
    rep = rep[rep.status == 'ok']                 # failed attempts are not results
    base = pd.read_csv(BASELINE, dtype=str, keep_default_na=False)
    base = base[base.run_id.str.startswith('baseline/') & (base.status == 'ok')]
    key = ['scenario', 'seed']
    pairs = rep.merge(base, on=key, suffixes=('_new', '_base'))
    rows = []
    for _, r in pairs.iterrows():
        row = {'scenario': r.scenario, 'seed': int(r.seed), 'run_new': r.run_id_new}
        for c in CATEGORICAL:
            row[f'{c}_base'], row[f'{c}_new'] = r[f'{c}_base'], r[f'{c}_new']
            row[f'{c}_same'] = same(r[f'{c}_base'], r[f'{c}_new'])
        for c in CONTINUOUS:
            a = pd.to_numeric(r[f'{c}_base'], errors='coerce')
            b = pd.to_numeric(r[f'{c}_new'], errors='coerce')
            row[f'{c}_base'], row[f'{c}_new'] = a, b
            row[f'{c}_diff'] = b - a
        rows.append(row)
    df = pd.DataFrame(rows).sort_values(key)
    df.to_csv(os.path.join(out, 'runs.csv'), index=False)

    n = len(df)
    lines = ['# Reproduction on the replacement machine: run-by-run comparison with the baseline', '',
             f'Generated by `evaluation/scripts/compare_repro.py` from `{os.path.relpath(repro_path, ROOT)}` '
             f'and the baseline `evaluation/data/metrics.csv`. Pairs: **{n}** '
             f'(same scenario and seed; reproduction runs not yet valid are absent).', '',
             '## Categorical agreement', '',
             '| Quantity | same in | share | Wilson 95 % CI |', '|---|---|---|---|']
    for c in CATEGORICAL:
        k = int(df[f'{c}_same'].sum()) if n else 0
        lo, hi = wilson(k, n)
        lines.append(f'| {c} | {k} / {n} | {k / n:.3f} | [{lo:.3f}, {hi:.3f}] |' if n else f'| {c} | 0 / 0 | – | – |')
    lines += ['', '## Per scenario', '',
              '| Scenario | pairs | outcome same | depth same | baseline outcomes | new outcomes |',
              '|---|---|---|---|---|---|']
    for s, g in df.groupby('scenario'):
        lines.append(f"| {s} | {len(g)} | {int(g.outcome_same.sum())} | {int(g.escalation_depth_same.sum())} | "
                     f"{', '.join(g.outcome_base)} | {', '.join(g.outcome_new)} |")
    lines += ['', '## Continuous metrics: new − baseline (pairs where both are defined)', '',
              '| Metric | pairs | median diff | median abs diff | max abs diff | baseline median | new median |',
              '|---|---|---|---|---|---|---|']
    for c in CONTINUOUS:
        d = df[f'{c}_diff'].dropna()
        if d.empty:
            continue
        lines.append(f'| {c} | {len(d)} | {d.median():+.3f} | {d.abs().median():.3f} | {d.abs().max():.3f} | '
                     f"{df[f'{c}_base'].dropna().median():.3f} | {df[f'{c}_new'].dropna().median():.3f} |")
    diff = df[~df.outcome_same | ~df.escalation_depth_same]
    lines += ['', '## Pairs that differ in outcome or escalation depth', '']
    if diff.empty:
        lines.append('None.')
    else:
        lines += ['| Scenario | seed | baseline outcome (depth) | new outcome (depth) |', '|---|---|---|---|']
        for _, r in diff.iterrows():
            lines.append(f'| {r.scenario} | {r.seed} | {r.outcome_base} ({r.escalation_depth_base}) | '
                         f'{r.outcome_new} ({r.escalation_depth_new}) |')
    with open(os.path.join(out, 'summary.md'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
