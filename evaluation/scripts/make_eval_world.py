#!/usr/bin/env python3
"""Generate src/yoru_bringup/worlds/eval_two_room.world from two_room_world.world.

The scripted 'person_smoking' actor is replaced by ROS-driven actors
(yoru_sim_plugins/yoru_actor_plugin) person_1..person_3 and intruder_1, each
with a collision body so the lidar, costmaps and e-stop see them. They start
parked outside the building; human_actor_node teleports the ones a scenario
uses into room A. Everything else (walls, cameras, the room-B walker, the
model-state plugin) is identical to the demo world.

Usage: python3 evaluation/scripts/make_eval_world.py
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WORLDS = os.path.join(ROOT, 'src', 'yoru_bringup', 'worlds')

ACTORS = [  # name, parked position (outside the 12 x 8 m building), walk speed
    ('person_1', (8.0, 6.0), 0.6),
    ('person_2', (9.0, 6.0), 0.6),
    ('person_3', (10.0, 6.0), 0.6),
    ('intruder_1', (11.0, 6.0), 1.2),
]

ACTOR_SDF = '''    <actor name="{name}">
      <pose>{x} {y} 0 0 0 0</pose>
      <skin><filename>walk.dae</filename><scale>1.0</scale></skin>
      <animation name="walking">
        <filename>walk.dae</filename><scale>1.0</scale>
        <interpolate_x>true</interpolate_x>
      </animation>
      <animation name="standing"><filename>stand.dae</filename><scale>1.0</scale></animation>
      <plugin name="yoru_actor_{name}" filename="libyoru_actor_plugin.so">
        <walk_speed>{speed}</walk_speed>
      </plugin>
    </actor>
    <!-- lidar/costmap-visible body of {name}, moved by the actor plugin -->
    <model name="{name}_body">
      <static>true</static>
      <pose>{x} {y} 0 0 0 0</pose>
      <link name="link">
        <collision name="body">
          <pose>0 0 0.85 0 0 0</pose>
          <geometry><cylinder><radius>0.2</radius><length>1.7</length></cylinder></geometry>
        </collision>
      </link>
    </model>
'''


def main():
    src = open(os.path.join(WORLDS, 'two_room_world.world'), encoding='utf-8').read()
    start = src.index('    <!-- Room A: standing person')
    end = src.index('</actor>', src.index('<actor name="person_smoking">')) + len('</actor>\n')
    people = ('    <!-- Evaluation people: ROS-driven actors (yoru_actor_plugin) with\n'
              '         collision bodies; positioned by human_actor_node -->\n'
              + ''.join(ACTOR_SDF.format(name=n, x=p[0], y=p[1], speed=s)
                        for n, p, s in ACTORS))
    world = src[:start] + people + src[end:]
    world = world.replace(
        '<?xml version="1.0"?>',
        '<?xml version="1.0"?>\n<!-- GENERATED by evaluation/scripts/make_eval_world.py'
        ' from two_room_world.world - do not edit by hand -->', 1)
    out = os.path.join(WORLDS, 'eval_two_room.world')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(world)
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
